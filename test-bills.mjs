import assert from 'node:assert/strict';
import {billSchema,billPlanSchema,billState} from './app/bills-data.ts';
const b={month:'2026-10',name:'Electricity',category:'Electricity Bill',amount:123456,dueDate:'2026-10-28',paid:false,datePaid:null,variable:true,note:'',transactionId:null};
assert.equal(billSchema.safeParse(b).success,true);
assert.equal(billSchema.safeParse({...b,dueDate:'2026-02-30'}).success,false);
assert.equal(billSchema.safeParse({...b,amount:1.5}).success,false);
assert.equal(billSchema.safeParse({...b,amount:-1}).success,false);
assert.equal(billSchema.safeParse({...b,datePaid:'2026-10-14'}).success,false);
assert.equal(billSchema.safeParse({...b,amount:null,dueDate:null}).success,true);
assert.equal(billState(b,[],'2026-10-29').status,'Overdue');
assert.equal(billState(b,[],'2026-10-28').status,'Due today');
assert.equal(billState({...b,paid:true},[],'2026-10-29').status,'Paid');
assert.equal(billState({...b,dueDate:null},[]).status,'Date needed');
const rows=[{id:'payment',kind:'transaction',version:1,payload:{group:'Bills',amount:123456,date:'2026-10-15'}}];
assert.equal(billState({...b,transactionId:'payment'},rows).datePaid,'2026-10-15');
assert.equal(billState({...b,transactionId:'payment'},rows).paid,true);
assert.equal(billState({...b,transactionId:'deleted'},rows).missingPayment,true);
assert.equal(billState({...b,transactionId:'payment'},[{...rows[0],payload:{...rows[0].payload,group:'Income'}}]).paid,false);
assert.equal(billPlanSchema.safeParse({month:'2026-13',emergency:0,wedding:0,savings:0}).success,false);
console.log('PASS: bill dates, currency precision, unknown amounts, paid/overdue states, payment links and monthly targets.');
